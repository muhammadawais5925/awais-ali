import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# 1. Create a sample dataset for EDA (Replace this with your own dataset, e.g., pd.read_csv('your_file.csv'))
data = {
    'Category': ['Electronics', 'Clothing', 'Electronics', 'Home & Kitchen', 'Clothing', 'Electronics', 'Books', 'Home & Kitchen', 'Books', 'Electronics'],
    'Price': [1200, 50, 800, 300, 80, 1500, 20, 150, 15, 600],
    'Quantity': [1, 2, 1, 1, 3, 1, 5, 2, 10, 2],
    'Rating': [4.5, 4.0, 4.8, 3.9, 4.2, 4.7, 4.1, 4.0, 4.5, 4.3]
}
df = pd.DataFrame(data)

# 2. Basic EDA
print("--- Dataset Info ---")
print(df.info())
print("\n--- Summary Statistics ---")
print(df.describe(include='all'))
print("\n--- Missing Values ---")
print(df.isnull().sum())

# 3. Pie Chart visualization of categorical distribution
plt.figure(figsize=(12, 6))

# Pie Chart 1: Distribution of items across Categories
plt.subplot(1, 2, 1)
category_counts = df['Category'].value_counts()
plt.pie(category_counts, labels=category_counts.index, autopct='%1.1f%%', startangle=140, colors=sns.color_palette('pastel'))
plt.title('Distribution of Sales Categories')

# Pie Chart 2: Total revenue distribution across Categories
plt.subplot(1, 2, 2)
df['Revenue'] = df['Price'] * df['Quantity']
revenue_by_category = df.groupby('Category')['Revenue'].sum()
plt.pie(revenue_by_category, labels=revenue_by_category.index, autopct='%1.1f%%', startangle=140, colors=sns.color_palette('Set2'))
plt.title('Revenue Contribution by Category')

plt.tight_layout()
plt.show()

from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report

# Ensure the 'Revenue' column is defined from the previous cell
if 'Revenue' not in df.columns:
    df['Revenue'] = df['Price'] * df['Quantity']

# 1. Define Features (X) and Target (y)
features = ['Price', 'Quantity', 'Rating', 'Revenue']
X = df[features]
y = df['Category']

# 2. Split into 80% training and 20% testing
# We remove stratify=y here because the test set size (2) is less than the number of unique classes (4)
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42
)

print(f"Training features shape: {X_train.shape}")
print(f"Testing features shape: {X_test.shape}\n")

# 3. Train a Random Forest Classifier
model = RandomForestClassifier(random_state=42, n_estimators=10)
model.fit(X_train, y_train)

# 4. Predict on the test set
y_pred = model.predict(X_test)

# 5. Accuracy and Classification Report
accuracy = accuracy_score(y_test, y_pred)
print(f"Model Accuracy: {accuracy * 100:.2f}%\n")
print("Classification Report:")
print(classification_report(y_test, y_pred, zero_division=0))

